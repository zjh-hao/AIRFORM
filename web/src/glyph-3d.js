function polyShape(pts, scale = 1) {
  const s = new Shape();
  s.moveTo(pts[0][0] * scale, pts[0][1] * scale);
  for (let i = 1; i < pts.length; i++) {
    s.lineTo(pts[i][0] * scale, pts[i][1] * scale);
  }
  s.closePath();
  return s;
}

function addHole(shape, pts, scale = 1) {
  const h = new Path();
  h.moveTo(pts[0][0] * scale, pts[0][1] * scale);
  for (let i = 1; i < pts.length; i++) {
    h.lineTo(pts[i][0] * scale, pts[i][1] * scale);
  }
  h.closePath();
  shape.holes.push(h);
}

function extrudeSolid(shape, scale) {
  const depth = Math.max(0.14, scale * 0.28);
  const bevel = Math.min(depth * 0.16, scale * 0.04);
  const geo = new ExtrudeGeometry(shape, {
    depth,
    bevelEnabled: true,
    bevelThickness: bevel,
    bevelSize: bevel * 0.85,
    bevelSegments: 1,
    curveSegments: 8,
  });
  geo.center();
  return geo;
}

function circlePath(cx, cy, r, segments = 24, cw = true) {
  const pts = [];
  for (let i = 0; i < segments; i++) {
    const a = (i / segments) * Math.PI * 2 * (cw ? -1 : 1);
    pts.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]);
  }
  return pts;
}

function crescentShape(r) {
  const pts = [];
  const aTop = Math.PI * 0.42;
  const aBot = Math.PI * 1.58;
  for (let i = 0; i <= 28; i++) {
    const a = aTop + (i / 28) * (aBot - aTop);
    pts.push([Math.cos(a) * r * 0.95, Math.sin(a) * r * 1.02]);
  }
  for (let i = 0; i <= 24; i++) {
    const a = Math.PI * 1.46 - (i / 24) * (Math.PI * 0.92);
    pts.push([0.36 * r + Math.cos(a) * r * 0.72, Math.sin(a) * r * 0.88]);
  }
  return polyShape(pts);
}

function starShape(r, spikes = 5, innerRatio = 0.43) {
  const pts = [];
  for (let i = 0; i < spikes * 2; i++) {
    const a = Math.PI / 2 + (i * Math.PI) / spikes;
    const rad = i % 2 === 0 ? r : r * innerRatio;
    pts.push([Math.cos(a) * rad, Math.sin(a) * rad]);
  }
  return polyShape(pts);
}

function cloudShape(r) {
  const pts = [[-0.78, -0.34], [0.76, -0.34]];
  const bumps = [
    { cx: 0.56, cy: -0.06, rad: 0.30, a0: -0.35 * Math.PI, a1: 0.48 * Math.PI },
    { cx: 0.20, cy: 0.24, rad: 0.34, a0: 0.05 * Math.PI, a1: 0.78 * Math.PI },
    { cx: -0.22, cy: 0.28, rad: 0.38, a0: 0.12 * Math.PI, a1: 0.88 * Math.PI },
    { cx: -0.58, cy: -0.02, rad: 0.32, a0: 0.38 * Math.PI, a1: 1.32 * Math.PI },
  ];
  for (const b of bumps) {
    for (let i = 0; i <= 8; i++) {
      const a = b.a0 + (i / 8) * (b.a1 - b.a0);
      pts.push([b.cx + Math.cos(a) * b.rad, b.cy + Math.sin(a) * b.rad]);
    }
  }
  return polyShape(pts, r);
}

function flowerShape(r) {
  const pts = [];
  const count = 48;
  for (let i = 0; i < count; i++) {
    const a = (i / count) * Math.PI * 2;
    const rad = r * (0.58 + 0.38 * Math.abs(Math.cos(2.5 * a)));
    pts.push([Math.cos(a) * rad, Math.sin(a) * rad]);
  }
  const shape = polyShape(pts);
  addHole(shape, circlePath(0, 0, r * 0.22, 14, true));
  return shape;
}

function butterflyShape(r) {
  const pts = [
    [0.0, 0.28], [0.10, 0.52], [0.58, 0.72], [0.88, 0.45], [0.80, 0.08],
    [0.42, -0.04], [0.68, -0.30], [0.56, -0.68], [0.16, -0.55], [0.06, -0.32],
    [0.0, -0.58],
    [-0.06, -0.32], [-0.16, -0.55], [-0.56, -0.68], [-0.68, -0.30], [-0.42, -0.04],
    [-0.80, 0.08], [-0.88, 0.45], [-0.58, 0.72], [-0.10, 0.52],
  ];
  return polyShape(pts, r);
}

function smileyShape(r) {
  const outer = polyShape(circlePath(0, 0, r, 28, false));
  addHole(outer, circlePath(-0.32 * r, 0.24 * r, 0.13 * r, 10, true));
  addHole(outer, circlePath(0.32 * r, 0.24 * r, 0.13 * r, 10, true));
  const smilePts = [];
  for (let i = 0; i <= 14; i++) {
    const a = -Math.PI * 0.82 + (i / 14) * (Math.PI * 0.64);
    smilePts.push([Math.cos(a) * 0.52 * r, Math.sin(a) * 0.46 * r - 0.05 * r]);
  }
  for (let i = 14; i >= 0; i--) {
    const a = -Math.PI * 0.82 + (i / 14) * (Math.PI * 0.64);
    smilePts.push([Math.cos(a) * 0.37 * r, Math.sin(a) * 0.31 * r - 0.05 * r]);
  }
  addHole(outer, smilePts);
  return outer;
}

function heartShape(r) {
  const pts = [];
  const count = 44;
  for (let i = 0; i < count; i++) {
    const t = (i / count) * Math.PI * 2;
    const x = (16 * Math.sin(t) ** 3) / 16.5;
    const y = (13 * Math.cos(t) - 5 * Math.cos(2 * t) - 2 * Math.cos(3 * t) - Math.cos(4 * t)) / 15.5;
    pts.push([x * r, y * r]);
  }
  return polyShape(pts);
}

export function buildPatternGeometry(type, radius = 0.65) {
  const r = Math.max(0.28, Math.min(2.2, radius));
  switch (type) {
    case 'moon': return extrudeSolid(crescentShape(r), r);
    case 'star': return extrudeSolid(starShape(r, 5, 0.42), r);
    case 'cloud': return extrudeSolid(cloudShape(r), r);
    case 'lightning': return extrudeSolid(polyShape([
      [0.24, 0.96], [-0.42, 0.04], [0.04, 0.04], [-0.26, -0.96], [0.46, -0.06], [0.02, -0.06],
    ], r), r);
    case 'sun': return extrudeSolid(starShape(r, 10, 0.60), r);
    case 'diamond': {
      const geo = new OctahedronGeometry(r * 0.92, 0);
      geo.scale(0.86, 1.15, 0.72);
      return geo;
    }
    case 'hexagon': {
      const geo = new CylinderGeometry(r * 0.86, r * 0.86, r * 0.38, 6);
      geo.rotateX(Math.PI / 2);
      return geo;
    }
    case 'crown': return extrudeSolid(polyShape([
      [-0.86, -0.52], [-0.92, 0.56], [-0.44, 0.04], [0.0, 0.76], [0.44, 0.04], [0.92, 0.56], [0.86, -0.52],
    ], r), r);
    case 'house': return extrudeSolid(polyShape([
      [0.0, 0.90], [0.84, 0.16], [0.68, 0.16], [0.68, -0.78], [-0.68, -0.78], [-0.68, 0.16], [-0.84, 0.16],
    ], r), r);
    case 'flower': return extrudeSolid(flowerShape(r), r);
    case 'tree': return extrudeSolid(polyShape([
      [0.0, 0.96], [0.56, 0.24], [0.28, 0.24], [0.74, -0.34], [0.16, -0.34],
      [0.16, -0.88], [-0.16, -0.88], [-0.16, -0.34], [-0.74, -0.34], [-0.28, 0.24], [-0.56, 0.24],
    ], r), r);
    case 'umbrella': {
      const pts = [];
      for (let i = 0; i <= 18; i++) {
        const a = Math.PI - (i / 18) * Math.PI;
        pts.push([Math.cos(a) * 0.92, 0.14 + Math.sin(a) * 0.66]);
      }
      pts.push([0.11, 0.14], [0.11, -0.62], [-0.04, -0.84], [-0.34, -0.74], [-0.24, -0.56], [-0.11, -0.62], [-0.11, 0.14]);
      return extrudeSolid(polyShape(pts, r), r);
    }
    case 'butterfly': return extrudeSolid(butterflyShape(r), r);
    case 'snowflake': return extrudeSolid(starShape(r, 6, 0.34), r);
    case 'smiley': return extrudeSolid(smileyShape(r), r);
    case 'hourglass': return extrudeSolid(polyShape([
      [-0.72, 0.88], [0.72, 0.88], [0.72, 0.62], [0.16, 0.0], [0.72, -0.62], [0.72, -0.88],
      [-0.72, -0.88], [-0.72, -0.62], [-0.16, 0.0], [-0.72, 0.62],
    ], r), r);
    case 'heart': return extrudeSolid(heartShape(r), r);
    default: return extrudeSolid(starShape(r, 5, 0.45), r);
  }
}

