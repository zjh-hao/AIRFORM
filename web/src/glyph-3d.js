export function buildLetterGeometry(rawChar, radius = 0.65) {
  const ch = String(rawChar || 'A').trim().toUpperCase().slice(0, 1);
  const spec = LETTER_GLYPHS[ch] || LETTER_GLYPHS.A;
  const scale = Math.max(0.28, Math.min(2.2, radius));
  const shape = polyShape(spec.outer, scale);
  if (Array.isArray(spec.holes)) {
    for (const hole of spec.holes) {
      addHole(shape, hole, scale);
    }
  }
  return extrudeSolid(shape, scale);
}
